#!/usr/bin/env python3
"""rtl/top/patch_top.py — make the titan-axi top from the pinned Earl Grey top.

Copies vendor/opentitan/hw/top_earlgrey/rtl/autogen/top_earlgrey.sv to
rtl/top/top_earlgrey.sv and replaces exactly two instances:

    xbar_main u_xbar_main (...);
    xbar_peri u_xbar_peri (...);

with one

    titan_axi_fabric u_axi_fabric (...);

reusing their port connections. The TL-UL link between the two crossbars
(main_tl_peri_req/rsp) disappears: inside the fabric it is AXI. Nothing else
in the file changes; run `diff` against the vendor file to see.

Re-run after the OpenTitan pin moves:  rtl/top/patch_top.py
"""

import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SRC = ROOT / "vendor/opentitan/hw/top_earlgrey/rtl/autogen/top_earlgrey.sv"
DST = HERE / "top_earlgrey.sv"


def grab_instance(text, module, inst):
    """Return (start, end, [(port, expr), ...]) for 'module inst ( ... );'."""
    m = re.search(rf"^  {module} {inst} \(\n(.*?)^  \);\n", text, re.M | re.S)
    if not m:
        sys.exit(f"instance '{module} {inst}' not found in {SRC}")
    # ".port (expr)" or the implicit ".port" form (connects to the same-named signal).
    conns = [(p, e if e else p) for p, e in
             re.findall(r"^\s*\.(\w+)\s*(?:\((.*?)\))?\s*,?\s*$", m.group(1), re.M)]
    return m.start(), m.end(), conns


def main():
    text = SRC.read_text()
    s_main, e_main, main_conns = grab_instance(text, "xbar_main", "u_xbar_main")
    s_peri, e_peri, peri_conns = grab_instance(text, "xbar_peri", "u_xbar_peri")
    assert s_main < s_peri

    # The main<->peri link and the peri crossbar's own clock/reset/scanmode go away:
    # inside the fabric the peri side runs on clk_fixed_i (the same clock).
    link_main = {"tl_peri_o", "tl_peri_i"}
    peri_only = {"clk_peri_i", "rst_peri_ni", "tl_main_i", "tl_main_o", "scanmode_i"}
    clk_peri = dict(peri_conns)["clk_peri_i"]
    clk_fixed = dict(main_conns)["clk_fixed_i"]
    if clk_peri != clk_fixed:
        sys.exit(f"xbar_peri clock ({clk_peri}) differs from xbar_main clk_fixed_i ({clk_fixed}); "
                 "the fabric assumes they are the same")

    conns = [(p, e) for p, e in main_conns if p not in link_main and p != "scanmode_i"]
    conns += [(p, e) for p, e in peri_conns if p not in peri_only]
    conns += [("scanmode_i", dict(main_conns)["scanmode_i"])]

    width = max(len(p) for p, _ in conns)
    body = ",\n".join(f"    .{p:<{width}} ({e})" for p, e in conns)
    inst = ("  // titan-axi: xbar_main + xbar_peri replaced by one AXI4 fabric\n"
            "  // (rtl/fabric/titan_axi_fabric.sv, generated by rtl/fabric/gen_fabric.py).\n"
            "  titan_axi_fabric u_axi_fabric (\n" + body + "\n  );\n")

    between = text[e_main:s_peri]
    out = text[:s_main] + inst + between + text[e_peri:]

    header = ("// titan-axi: GENERATED by rtl/top/patch_top.py from\n"
              "//   vendor/opentitan/hw/top_earlgrey/rtl/autogen/top_earlgrey.sv\n"
              "// The only change: the two TL-UL crossbar instances are replaced by\n"
              "// titan_axi_fabric. Do not edit; re-run the script.\n")
    DST.write_text(header + out)
    print(f"{DST.relative_to(ROOT)}: {len(main_conns)} + {len(peri_conns)} xbar connections "
          f"-> {len(conns)} fabric connections")


if __name__ == "__main__":
    main()
