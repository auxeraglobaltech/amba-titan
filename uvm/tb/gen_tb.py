#!/usr/bin/env python3
"""uvm/tb/gen_tb.py — testbench files generated from the fabric description.

Reads rtl/fabric/fabric_ports.json (written by rtl/fabric/gen_fabric.py) and writes

  uvm/tb/titan_axi_probe.sv         one axi_if per fabric port, bound into
                                    titan_axi_fabric and published to the
                                    uvm_config_db as "axi_vif:<port>"
  uvm/env/titan_addr_map_pkg.sv     decode(addr) -> device port, and which
                                    devices each host may reach

Same source as the RTL, so the testbench's idea of the address map can never
disagree with the design's. Re-run whenever gen_fabric.py is re-run.
"""

import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
PORTS_JSON = ROOT / "rtl/fabric/fabric_ports.json"
OUT_PROBE = HERE / "titan_axi_probe.sv"
OUT_MAP = ROOT / "uvm/env/titan_addr_map_pkg.sv"

FAB = "titan_axi_fabric"   # upward reference into the bound fabric instance


def ident(port):
    return "if_" + re.sub(r"[^A-Za-z0-9]", "_", port)


def fab_ref(expr):
    """'peri_dev_req[PeriDevUart0]' -> 'titan_axi_fabric.peri_dev_req[titan_axi_fabric.PeriDevUart0]'."""
    m = re.fullmatch(r"(\w+)(?:\[(\w+)\])?", expr)
    base, idx = m.group(1), m.group(2)
    if idx is None:
        return f"{FAB}.{base}"
    if idx.isdigit():
        return f"{FAB}.{base}[{idx}]"
    return f"{FAB}.{base}[{FAB}.{idx}]"


def main():
    j = json.loads(PORTS_JSON.read_text())
    ports = j["ports"]
    hosts = j["main_hosts"]
    conn = j["connectivity"]

    # ------------------------------------------------------------------ probe
    L = []
    w = L.append
    w("// titan_axi_probe — GENERATED by uvm/tb/gen_tb.py from rtl/fabric/fabric_ports.json.")
    w("// Do not edit.")
    w("//")
    w("// Bound into titan_axi_fabric (see the bind at the bottom). For every AXI port")
    w("// of the fabric it instantiates an axi_if, wires it to the port's req/rsp")
    w("// structs, and publishes it as uvm_config_db #(virtual axi_if) \"axi_vif:<port>\".")
    w("//")
    w("// Monitored ports are read-only. The one exception is host.sim_host: there the")
    w("// interface's master-side signals are FORCED onto the fabric's sim_host_req, so")
    w("// a UVM driver can act as a bus master (stub-CPU tests).")
    w("")
    w("module titan_axi_probe;")
    w("  import uvm_pkg::*;")
    w("  import titan_axi_pkg::*;")
    w("")
    for p in ports:
        n = ident(p["name"])
        req, rsp = fab_ref(p["req"]), fab_ref(p["rsp"])
        clk, rst = f"{FAB}.{p['clock']}", f"{FAB}.{p['reset']}"
        driven = p["name"] == "host.sim_host"
        w(f"  // {p['name']}  ({p['clock']}{', driven by the testbench' if driven else ''})")
        w(f"  axi_if {n} (.aclk({clk}), .aresetn({rst}));")
        resp_side = [
            ("awready", f"{rsp}.aw_ready"), ("wready", f"{rsp}.w_ready"),
            ("bid", f"{rsp}.b.id"), ("bresp", f"{rsp}.b.resp"), ("bvalid", f"{rsp}.b_valid"),
            ("arready", f"{rsp}.ar_ready"),
            ("rid", f"{rsp}.r.id"), ("rdata", f"{rsp}.r.data"), ("rresp", f"{rsp}.r.resp"),
            ("rlast", f"{rsp}.r.last"), ("rvalid", f"{rsp}.r_valid"),
        ]
        req_side = [
            ("awid", f"{req}.aw.id"), ("awaddr", f"{req}.aw.addr"), ("awlen", f"{req}.aw.len"),
            ("awsize", f"{req}.aw.size"), ("awburst", f"{req}.aw.burst"), ("awprot", f"{req}.aw.prot"),
            ("awvalid", f"{req}.aw_valid"),
            ("wdata", f"{req}.w.data"), ("wstrb", f"{req}.w.strb"), ("wlast", f"{req}.w.last"),
            ("wvalid", f"{req}.w_valid"), ("bready", f"{req}.b_ready"),
            ("arid", f"{req}.ar.id"), ("araddr", f"{req}.ar.addr"), ("arlen", f"{req}.ar.len"),
            ("arsize", f"{req}.ar.size"), ("arburst", f"{req}.ar.burst"), ("arprot", f"{req}.ar.prot"),
            ("arvalid", f"{req}.ar_valid"), ("rready", f"{req}.r_ready"),
        ]
        for sig, src in resp_side:
            w(f"  assign {n}.{sig} = {src};")
        if not driven:
            for sig, src in req_side:
                w(f"  assign {n}.{sig} = {src};")
        else:
            w("  host_req_t sim_host_drv;")
            w("  always_comb begin")
            w("    sim_host_drv = HOST_REQ_IDLE;")
            for sig, dst in req_side:
                field = dst[len(req) + 1:]
                if sig.endswith("valid") or sig.endswith("ready"):
                    w(f"    sim_host_drv.{field} = ({n}.{sig} === 1'b1);   // X -> 0")
                elif sig in ("awid", "arid"):
                    w(f"    sim_host_drv.{field} = {n}.{sig}[HostIdWidth-1:0];")
                else:
                    w(f"    sim_host_drv.{field} = {n}.{sig};")
            w("    // AxUSER stays 0: intg_vld = 0, so the device bridges generate TL-UL integrity.")
            w("  end")
            w(f"  initial force {req} = sim_host_drv;")
        w("")
    w("  initial begin")
    for p in ports:
        w(f"    uvm_config_db #(virtual axi_if)::set(null, \"\", \"axi_vif:{p['name']}\", {ident(p['name'])});")
    w("  end")
    w("endmodule")
    w("")
    w(f"bind {FAB} titan_axi_probe u_titan_axi_probe ();")
    OUT_PROBE.write_text("\n".join(L) + "\n")

    # ---------------------------------------------------------------- addr map
    devs = [p for p in ports if p["kind"] == "dev"]
    M = []
    m = M.append
    m("// titan_addr_map_pkg — GENERATED by uvm/tb/gen_tb.py from rtl/fabric/fabric_ports.json.")
    m("// Do not edit.")
    m("//")
    m("// The fabric's address map and connectivity, for checkers:")
    m("//   decode(addr)          device port that owns addr, or \"\" (-> DECERR)")
    m("//   reachable(host, dev)  may this host reach that device? (else DECERR)")
    m("//   host_name(idx)        the host behind the index the crossbar prepends")
    m("//                         to device-side IDs (id[5:4])")
    m("")
    m("package titan_addr_map_pkg;")
    m("")
    m(f"  localparam int unsigned NumPorts = {len(ports)};")
    m("  localparam string PortNames[NumPorts] = '{")
    m(",\n".join(f'    "{p["name"]}"' for p in ports))
    m("  };")
    m("")
    m("  function automatic string host_name(int unsigned idx);")
    m("    case (idx)")
    for i, h in enumerate(hosts):
        m(f'      {i}: return "host.{h}";')
    m('      default: return "";')
    m("    endcase")
    m("  endfunction")
    m("")
    m("  function automatic string decode(bit [31:0] addr);")
    for p in devs:
        for lo, hi in p["ranges"]:
            m(f"    if (addr >= 32'h{int(lo, 16):08x} && addr < 32'h{int(hi, 16):08x}) "
              f"return \"{p['name']}\";")
    m('    return "";')
    m("  endfunction")
    m("")
    m("  function automatic bit reachable(string host, string dev);")
    m("    case (host)")
    for h in hosts:
        reach = set(conn[h])
        names = [p["name"] for p in devs
                 if (p["xbar"] == "main" and p["name"][4:] in reach)
                 or (p["xbar"] == "peri" and "peri" in reach)]
        m(f'      "host.{h}": return dev inside {{')
        m(",\n".join(f'        "{n}"' for n in names) + "};")
    m("      default: return 0;")
    m("    endcase")
    m("  endfunction")
    m("")
    m("endpackage")
    OUT_MAP.write_text("\n".join(M) + "\n")

    print(f"{OUT_PROBE.relative_to(ROOT)}: {len(ports)} axi_if instances")
    print(f"{OUT_MAP.relative_to(ROOT)}: {sum(len(p['ranges']) for p in devs)} address ranges, "
          f"{len(hosts)} hosts")


if __name__ == "__main__":
    main()
